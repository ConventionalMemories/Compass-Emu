/// Name of call `n` through vector `vec` (70h OS, 71h CP, 72h Pascal runtime, 73h Common).
pub fn name(vec: u8, n: u8) -> Option<&'static str> {
    let t: &[&str] = match vec {
        0x70 => &INT70,
        0x71 => &INT71,
        0x72 => &INT72,
        0x73 => &INT73,
        _ => return None,
    };
    t.get(n as usize).copied().filter(|s| !s.is_empty())
}
