/// Lit LED colour (the real display is red).
pub const LIT: Color32 = Color32::from_rgb(0xFF, 0x2A, 0x1A);
const DIM: Color32 = Color32::from_rgb(0x30, 0x0C, 0x0A);
const GLASS: Color32 = Color32::from_rgb(0x14, 0x05, 0x04);

fn glyph(c: char) -> [u8; 5] {
    let i = c as u32;
    if (0x20..0x7F).contains(&i) {
        FONT[(i - 0x20) as usize]
    }
    else {
        [0x7F, 0x41, 0x41, 0x41, 0x7F]
    }
}

/// Draw `text` (padded or cut to four characters) as the 2101 display, `dot` = pixel
/// spacing of one LED. Returns the response for hover text.
pub fn display(ui: &mut egui::Ui, text: &str, dot: f32) -> egui::Response {
    let chars: Vec<char> = text.chars().chain(std::iter::repeat(' ')).take(4).collect();
    let char_w = 6.0 * dot;
    let pad = dot * 1.2;
    let size = Vec2::new(4.0 * char_w - dot + 2.0 * pad, 7.0 * dot + 2.0 * pad);
    let (rect, resp) = ui.allocate_exact_size(size, Sense::click());
    let p = ui.painter_at(rect);
    p.rect_filled(rect, dot * 0.6, GLASS);
    let r = dot * 0.38;
    for (n, &c) in chars.iter().enumerate() {
        let g = glyph(c);
        for (col, bits) in g.iter().enumerate() {
            for row in 0..7 {
                let on = bits >> row & 1 != 0;
                let x = rect.min.x + pad + n as f32 * char_w + col as f32 * dot + dot * 0.5;
                let y = rect.min.y + pad + row as f32 * dot + dot * 0.5;
                let c = Pos2::new(x, y);
                if on {
                    if dot >= 4.0 {
                        p.circle_filled(c, r * 1.9, LIT.gamma_multiply(0.18));
                    }
                    p.circle_filled(c, r, LIT);
                }
                else {
                    p.circle_filled(c, r, DIM);
                }
            }
        }
    }
    resp
}

#[cfg(test)]
mod tests {
    #[test]
    fn letters_look_right() {
        // "H" and "I" as on the real display: H = two bars and a middle stroke, I with serifs.
        assert_eq!(super::glyph('H'), [0x7F, 0x08, 0x08, 0x08, 0x7F]);
        assert_eq!(super::glyph('I'), [0x00, 0x41, 0x7F, 0x41, 0x00]);
        assert_eq!(super::glyph('~'), [0x02, 0x01, 0x02, 0x04, 0x02]);
    }
}
