		NAME	CRASHASM

CGROUP		GROUP	CODE

CODE		SEGMENT	PUBLIC 'CODE'
		ASSUME	CS:CGROUP, DS:NOTHING, ES:NOTHING

		PUBLIC	DOINT3, DOWILD

DOINT3		PROC	NEAR
		PUSH	BP
		MOV	BP, SP
		INT	3
		NOP
		POP	BP
		RET
DOINT3		ENDP

DOWILD		PROC	NEAR
		PUSH	BP
		MOV	BP, SP
		MOV	AX, 7F00H
		PUSH	AX
		XOR	AX, AX
		PUSH	AX
		DB	0CBH		; RETF
DOWILD		ENDP

CODE		ENDS
		END
